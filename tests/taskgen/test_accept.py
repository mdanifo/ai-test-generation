"""The human gate: only accepted tests enter tests/generated/, with a header saying why."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

from taskgen.accept import AcceptError, accept, header
from taskgen.cards import number_criteria
from taskgen.gate import CardGate, TestOutcome, Verdict, gate_env, sha256, source_text, write_card

REPO = Path(__file__).resolve().parents[2]

CRITERIA = number_criteria(
    [
        'Given a caller says "agent", "representative" or "a real person", or presses 0, then '
        "Front Desk transfers in that turn without asking why.",
        "Given two caller turns in a row with speech recognition confidence below 0.6, then "
        "Front Desk offers a transfer.",
    ]
)


def code_for(name: str, criterion: str = "AC-1") -> str:
    return (
        "import pytest\n\n"
        "from harness import TRANSFER_LINE\n\n\n"
        f'@pytest.mark.criterion("FERN-8/{criterion}")\n'
        f"def {name}(call):\n"
        '    assert call.say("agent").text == TRANSFER_LINE\n'
    )


def outcome(index: int, name: str, verdict: Verdict, caught: tuple[str, ...] = ()) -> TestOutcome:
    code = code_for(name)
    folder = "FERN-8/rejected/FERN-8_" if verdict == Verdict.REJECTED else "FERN-8/test_FERN-8_"
    return TestOutcome(
        index=index,
        criterion="AC-1",
        name=name,
        intent=f"Fails if asking for a person does not transfer ({name}).",
        code=code,
        code_sha256=sha256(source_text(code)),
        file=f"{folder}{index}.py",
        verdict=verdict,
        reason=f"Gate reason for {name}.",
        caught=caught,
    )


TESTS = (
    outcome(1, "test_agent_transfers", Verdict.ACCEPTED, ("transfer-asks-why",)),
    outcome(2, "test_zero_transfers", Verdict.ACCEPTED, ("transfer-asks-why", "ssml-unescaped")),
    outcome(3, "test_reply_exists", Verdict.PROVES_NOTHING),
    outcome(4, "test_wrong_line", Verdict.FAILS_ON_CLEAN),
    outcome(5, "test_wobbly", Verdict.FLAKY),
    outcome(6, "test_sleepy", Verdict.REJECTED),
    outcome(7, "test_later", Verdict.NOT_BUILT_YET),
)


def gated(proposed: Path, tests: tuple[TestOutcome, ...] = TESTS) -> CardGate:
    """Write a gate record and its proposed files, as `taskgen gate` leaves them."""
    card = CardGate(
        card="FERN-8",
        title="Hand off to a person on request or when the agent is stuck",
        list_role="done",
        gated=True,
        criteria=CRITERIA,
        tests=tests,
        seeded_bugs=("transfer-asks-why", "ssml-unescaped"),
        generation={"card": "FERN-8", "status": "ok", "source": "canned", "output": None},
    )
    for test in tests:
        path = proposed / test.file
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source_text(test.code), encoding="utf-8")
    write_card(card, proposed)
    return card


@pytest.fixture
def dirs(tmp_path: Path) -> tuple[Path, Path]:
    proposed, generated = tmp_path / "proposed", tmp_path / "generated"
    gated(proposed)
    return proposed, generated


def files_in(directory: Path) -> list[str]:
    if not directory.exists():
        return []
    return sorted(p.relative_to(directory).as_posix() for p in directory.rglob("*") if p.is_file())


def test_two_accepted_tests_with_one_name_are_refused(tmp_path):
    proposed, generated = tmp_path / "proposed", tmp_path / "generated"
    twins = (
        outcome(1, "test_transfer", Verdict.ACCEPTED, ("transfer-asks-why",)),
        outcome(2, "test_transfer", Verdict.ACCEPTED, ("transfer-asks-why",)),
    )
    gated(proposed, twins)

    with pytest.raises(AcceptError, match="more than one accepted test named test_transfer"):
        accept("FERN-8", proposed_dir=proposed, generated_dir=generated)
    assert files_in(generated) == []


def test_accept_copies_every_accepted_test_with_a_header(dirs):
    proposed, generated = dirs

    done = accept("FERN-8", proposed_dir=proposed, generated_dir=generated)

    assert [(a.name, a.status) for a in done] == [
        ("test_agent_transfers", "written"),
        ("test_zero_transfers", "written"),
    ]
    assert files_in(generated) == [
        "FERN-8/test_agent_transfers.py",
        "FERN-8/test_zero_transfers.py",
    ]
    text = (generated / "FERN-8" / "test_agent_transfers.py").read_text()
    assert text.endswith("\n\n" + code_for("test_agent_transfers"))


def test_the_header_names_the_card_the_criterion_and_the_bugs_caught(dirs):
    proposed, generated = dirs
    accept("FERN-8", ["test_zero_transfers"], proposed_dir=proposed, generated_dir=generated)
    text = (generated / "FERN-8" / "test_zero_transfers.py").read_text()
    head = text.split("\n\n", 1)[0].splitlines()

    assert head[0] == (
        "# Generated by taskgen and accepted after review with `taskgen accept FERN-8`."
    )
    assert "# Card: FERN-8 · Hand off to a person on request or when the agent is stuck" in head
    assert head[2].startswith('# Criterion: FERN-8/AC-1 · Given a caller says "agent"')
    assert (
        "# Gate: passed the clean build twice; failed under seeded bugs: transfer-asks-why, "
        "ssml-unescaped."
    ) in head
    assert head[-1] == (
        "# Tests from: canned stand-ins in fixtures/canned/ (written for the offline demo, not "
        "model output)"
    )
    assert all(line.startswith("#") and len(line) <= 100 for line in head)


def test_accepting_the_same_test_twice_changes_nothing(dirs):
    proposed, generated = dirs
    accept("FERN-8", ["test_agent_transfers"], proposed_dir=proposed, generated_dir=generated)

    again = accept(
        "FERN-8", ["test_agent_transfers"], proposed_dir=proposed, generated_dir=generated
    )

    assert [(a.name, a.status) for a in again] == [("test_agent_transfers", "unchanged")]


@pytest.mark.parametrize(
    ("name", "verdict"),
    [
        ("test_reply_exists", "proves-nothing"),
        ("test_wrong_line", "fails-on-clean"),
        ("test_wobbly", "flaky"),
        ("test_sleepy", "rejected"),
        ("test_later", "not-built-yet"),
    ],
)
def test_a_test_that_was_not_accepted_is_refused(dirs, name, verdict):
    proposed, generated = dirs

    with pytest.raises(AcceptError) as refused:
        accept("FERN-8", [name], proposed_dir=proposed, generated_dir=generated)

    assert f"{name} is {verdict}: Gate reason for {name}." in str(refused.value)
    assert "Only accepted tests can enter the suite; nothing was copied." in str(refused.value)
    assert files_in(generated) == []


def test_one_refused_name_stops_the_whole_request(dirs):
    proposed, generated = dirs

    with pytest.raises(AcceptError, match="test_sleepy is rejected"):
        accept(
            "FERN-8",
            ["test_agent_transfers", "test_sleepy"],
            proposed_dir=proposed,
            generated_dir=generated,
        )

    assert files_in(generated) == []


def test_an_unknown_test_name_is_refused(dirs):
    proposed, generated = dirs

    with pytest.raises(AcceptError, match="FERN-8 has no proposed test 'test_nope'"):
        accept("FERN-8", ["test_nope"], proposed_dir=proposed, generated_dir=generated)


def test_a_card_with_no_accepted_test_is_refused(tmp_path):
    proposed, generated = tmp_path / "proposed", tmp_path / "generated"
    gated(proposed, TESTS[2:])

    with pytest.raises(AcceptError, match="FERN-8 has no accepted test to copy"):
        accept("FERN-8", proposed_dir=proposed, generated_dir=generated)
    assert files_in(generated) == []


def test_a_card_that_was_never_gated_is_refused(tmp_path):
    with pytest.raises(AcceptError, match="run `taskgen gate` for FERN-8 first"):
        accept("FERN-8", proposed_dir=tmp_path, generated_dir=tmp_path / "generated")


def test_a_proposed_file_edited_after_the_gate_is_refused(dirs):
    proposed, generated = dirs
    path = proposed / "FERN-8" / "test_FERN-8_1.py"
    path.write_text(path.read_text().replace("TRANSFER_LINE\n", "TRANSFER_LINE or True\n"))

    with pytest.raises(AcceptError, match="changed after the gate ran"):
        accept("FERN-8", proposed_dir=proposed, generated_dir=generated)
    assert files_in(generated) == []


def test_a_missing_proposed_file_is_refused(dirs):
    proposed, generated = dirs
    (proposed / "FERN-8" / "test_FERN-8_2.py").unlink()

    with pytest.raises(AcceptError, match="is missing"):
        accept("FERN-8", proposed_dir=proposed, generated_dir=generated)
    assert files_in(generated) == []


def test_a_different_test_already_at_the_target_is_never_overwritten(dirs):
    proposed, generated = dirs
    target = generated / "FERN-8" / "test_agent_transfers.py"
    target.parent.mkdir(parents=True)
    target.write_text("# a test someone already reviewed\n")

    with pytest.raises(AcceptError, match="already holds a different test"):
        accept("FERN-8", proposed_dir=proposed, generated_dir=generated)

    assert target.read_text() == "# a test someone already reviewed\n"
    assert files_in(generated) == ["FERN-8/test_agent_transfers.py"]


def test_an_accepted_test_runs_and_passes_against_the_app(dirs, tmp_path):
    proposed, generated = dirs
    (done,) = accept(
        "FERN-8", ["test_agent_transfers"], proposed_dir=proposed, generated_dir=generated
    )
    command = [
        sys.executable,
        "-m",
        "pytest",
        "-c",
        str(REPO / "pyproject.toml"),
        "--rootdir",
        str(tmp_path),
        done.path.relative_to(tmp_path).as_posix(),
        "-q",
        "-p",
        "no:cacheprovider",
    ]

    finished = subprocess.run(
        command, cwd=tmp_path, env=gate_env(None), capture_output=True, text=True, check=False
    )

    assert finished.returncode == 0, finished.stdout[-2000:]
    assert "1 passed" in finished.stdout


def test_header_is_a_comment_block_for_any_test(tmp_path):
    card = gated(tmp_path)

    assert all(line.startswith("#") for line in header(card, TESTS[0]).splitlines())
