"""The human gate: copy reviewed, accepted tests into the suite.

``taskgen accept <card> [--tests name,...]`` reads ``proposed/<card>/gate.json`` and
copies tests into ``tests/generated/<card>/<name>.py``, each with a header comment
naming the card, the criterion and the seeded bugs it caught. This module is the only
thing that writes to ``tests/generated/``.

It refuses, and copies nothing, when:

* a named test is not ``accepted`` (proves-nothing, fails-on-clean, flaky, rejected or
  not-built-yet tests never enter the suite);
* a named test does not exist, or the card has no accepted test at all;
* a proposed file changed after the gate ran (gate it again);
* a different test already sits at the target path (nothing is overwritten);
* two of the chosen tests share a name, so they would land on one path.

Accepting the same test twice is a no-op.

``check_suite`` is the other half: CI runs it over ``tests/generated/`` so a file there
that lost its header, or whose code no longer passes the static checks, fails the build.
Those files are kept exactly as the gate ran them, so ruff does not reformat them
(pyproject.toml excludes the directory); the static checks are their rules.
"""

from __future__ import annotations

import re
import textwrap
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

from taskgen.cards import Card
from taskgen.gate import (
    DEFAULT_PROPOSED,
    REPO,
    CardGate,
    TestOutcome,
    Verdict,
    load_card,
    sha256,
    source_text,
)
from taskgen.report import source_label
from taskgen.static_checks import check_code

GENERATED_DIR = REPO / "tests" / "generated"
HEADER_WIDTH = 100


class AcceptError(Exception):
    """A request to accept tests that the gate did not accept, or that changed since."""


@dataclass(frozen=True)
class Accepted:
    name: str
    path: Path
    status: Literal["written", "unchanged"]


def _wrapped(label: str, text: str) -> list[str]:
    return textwrap.wrap(
        text,
        width=HEADER_WIDTH,
        initial_indent=f"# {label}: ",
        subsequent_indent="#   ",
        break_on_hyphens=False,
    )


def header(card: CardGate, test: TestOutcome) -> str:
    """The comment block that opens an accepted test file."""
    caught = ", ".join(test.caught)
    lines = [
        f"# Generated by taskgen and accepted after review with `taskgen accept {card.card}`.",
        *_wrapped("Card", f"{card.card} · {card.title}"),
        *_wrapped(
            "Criterion", f"{card.card}/{test.criterion} · {card.criterion_text(test.criterion)}"
        ),
        *_wrapped("Intent", test.intent),
        *_wrapped(
            "Gate",
            f"passed the clean build twice; failed under seeded bugs: {caught}.",
        ),
        *_wrapped("Tests from", source_label(card.source)),
    ]
    return "\n".join(lines) + "\n"


def _choose(card: CardGate, names: Sequence[str] | None) -> list[TestOutcome]:
    if names is None:
        chosen = card.accepted()
        if not chosen:
            counts = ", ".join(f"{n} {v.value}" for v, n in card.counts().items() if n)
            raise AcceptError(
                f"{card.card} has no accepted test to copy ({counts or 'no tests'}). "
                f"See proposed/{card.card}/REPORT.md."
            )
        return chosen
    chosen = []
    refused = []
    for name in dict.fromkeys(names):
        try:
            test = card.test(name)
        except KeyError as exc:
            raise AcceptError(str(exc.args[0])) from None
        if test.verdict != Verdict.ACCEPTED:
            refused.append(f"{name} is {test.verdict.value}: {test.reason}")
        else:
            chosen.append(test)
    if refused:
        raise AcceptError(
            "Only accepted tests can enter the suite; nothing was copied.\n  "
            + "\n  ".join(refused)
        )
    return chosen


def accept(
    ref: str,
    tests: Sequence[str] | None = None,
    *,
    proposed_dir: Path = DEFAULT_PROPOSED,
    generated_dir: Path = GENERATED_DIR,
) -> list[Accepted]:
    """Copy ``ref``'s accepted tests (or only the named ones) into ``generated_dir/<ref>/``.

    Checks every test before writing any, so a refusal leaves the suite untouched.
    """
    try:
        card = load_card(ref, proposed_dir)
    except FileNotFoundError as exc:
        raise AcceptError(str(exc)) from None
    chosen = _choose(card, tests)
    names = [test.name for test in chosen]
    shared = sorted({name for name in names if names.count(name) > 1})
    if shared:
        raise AcceptError(
            f"{ref} has more than one accepted test named {', '.join(shared)}; each would be "
            f"written to tests/generated/{ref}/<name>.py, so nothing was copied. Rename one "
            "and gate the card again."
        )
    planned: list[tuple[TestOutcome, Path, str]] = []
    for test in chosen:
        source = Path(proposed_dir) / test.file
        if not source.exists():
            raise AcceptError(f"{source} is missing; run `taskgen gate` for {ref} again")
        code = source.read_text(encoding="utf-8")
        if sha256(code) != test.code_sha256 or code != source_text(test.code):
            raise AcceptError(
                f"{source} changed after the gate ran; run `taskgen gate` for {ref} again "
                "so the gate checks the code you mean to accept"
            )
        target = Path(generated_dir) / ref / f"{test.name}.py"
        content = header(card, test) + "\n" + code
        if target.exists() and target.read_text(encoding="utf-8") != content:
            raise AcceptError(
                f"{target} already holds a different test; nothing was copied. Remove it or "
                "rename the new test before accepting it."
            )
        planned.append((test, target, content))

    done = []
    for test, target, content in planned:
        if target.exists():
            done.append(Accepted(test.name, target, "unchanged"))
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        done.append(Accepted(test.name, target, "written"))
    return done


_CRITERION_LINE = re.compile(r"^# Criterion: (?P<ref>[A-Z][A-Z0-9]*-\d+)/(?P<id>AC-\d+) ")


def check_suite(generated_dir: Path, cards: Mapping[str, Card]) -> list[str]:
    """Problems with the accepted tests under ``generated_dir``, one line each.

    Every ``<card>/<name>.py`` must open with the header ``accept`` writes, name a card
    in ``cards`` and one of its criteria, and hold code that passes the static checks
    for that card under that name. An empty or missing directory has no problems.
    """
    problems: list[str] = []
    root = Path(generated_dir)
    for path in sorted(root.rglob("*.py")) if root.exists() else []:
        where = path.relative_to(root).as_posix()
        ref = path.parent.name
        if path.parent.parent != root:
            problems.append(f"{where}: accepted tests live in {root.name}/<card>/<name>.py")
            continue
        if ref not in cards:
            problems.append(f"{where}: {ref} is not a card on the board")
            continue
        head, _, code = path.read_text(encoding="utf-8").partition("\n\n")
        lines = head.splitlines()
        first = f"# Generated by taskgen and accepted after review with `taskgen accept {ref}`."
        if not lines or lines[0] != first or not all(line.startswith("#") for line in lines):
            problems.append(f"{where}: missing the header `taskgen accept` writes")
            continue
        found = [m for m in map(_CRITERION_LINE.match, lines) if m]
        if not found or found[0]["ref"] != ref:
            problems.append(f"{where}: the header names no criterion of {ref}")
            continue
        result = check_code(code, cards[ref], name=path.stem, criterion=found[0]["id"])
        problems += [f"{where}: {problem}" for problem in result.problems]
    return problems
